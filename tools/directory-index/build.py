#!/usr/bin/env python3
"""Generate static directory pages without changing existing websites or files."""

import html
import json
import tempfile
from pathlib import Path
from string import Template
from urllib.parse import quote


MARKER = "<!-- Generated by tools/directory-index/build.py; do not edit this file. -->"
TEMPLATE = Path(__file__).with_name("template.html")
DESCRIPTIONS = Path(__file__).with_name("descriptions.json")
REPOSITORY = Path(__file__).resolve().parents[2]
INDEX_NAMES = ("index.html", "index.htm", "index.php")


def is_generated(path):
    if not path.is_file() or path.is_symlink():
        return False
    with path.open("rb") as stream:
        return MARKER.encode("utf-8") in stream.read(2048)


def has_website_index(directory):
    for name in INDEX_NAMES:
        path = directory / name
        if (path.exists() or path.is_symlink()) and (name != "index.html" or not is_generated(path)):
            return True
    return False


def load_descriptions(path=DESCRIPTIONS):
    if not path.exists():
        return {}
    data = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(data, dict):
        raise ValueError("Directory descriptions must be grouped by public root.")
    for root, settings in data.items():
        if not isinstance(settings, dict):
            raise ValueError("Expected description settings for {}.".format(root))
        introduction = settings.get("intro")
        entries = settings.get("entries", {})
        if introduction is not None and not isinstance(introduction, str):
            raise ValueError("The intro for {} must be text or null.".format(root))
        if not isinstance(entries, dict):
            raise ValueError("The entries for {} must map paths to descriptions.".format(root))
        for value in entries.values():
            if isinstance(value, dict):
                for field in ("title", "authors", "date"):
                    if not isinstance(value.get(field), str) or not value[field].strip():
                        raise ValueError("Bibliographic entries for {} require title, authors, and date text.".format(root))
            elif value is not None and not isinstance(value, str):
                raise ValueError("Entries for {} must be text, null, or bibliographic records.".format(root))
    return data


def description_markup(value, class_name, tag="span"):
    if not isinstance(value, str) or not value.strip():
        return ""
    return '<{tag} class="{class_name}">{text}</{tag}>'.format(
        tag=tag, class_name=class_name, text=html.escape(value.strip())
    )


def entry_content(name, details, folder=False):
    if isinstance(details, dict) and not folder:
        return (
            '<span class="entry-name entry-title">{}</span>'
            '<span class="entry-authors">{}</span>'
            '<span class="entry-date">{}</span>'
            '<span class="entry-filename">{}</span>'
        ).format(
            html.escape(details["title"].strip()), html.escape(details["authors"].strip()),
            html.escape(details["date"].strip()), html.escape(name),
        )
    return '<span class="entry-name">{}</span>{}'.format(
        html.escape(name), description_markup(details, "entry-description")
    )


def file_size(size):
    amount = float(size)
    for unit in ("B", "KB", "MB", "GB", "TB"):
        if amount < 1024 or unit == "TB":
            number = str(int(amount)) if unit == "B" else "{:.1f}".format(amount).rstrip("0").rstrip(".")
            return "{} {}".format(number, unit)
        amount /= 1024


def write_if_changed(path, content):
    if path.exists() and path.read_text(encoding="utf-8") == content:
        return
    temporary = None
    try:
        with tempfile.NamedTemporaryFile(
            mode="w", encoding="utf-8", dir=str(path.parent),
            prefix=".index-", suffix=".tmp", delete=False
        ) as stream:
            stream.write(content)
            temporary = Path(stream.name)
        temporary.chmod(0o644)
        temporary.replace(path)
    finally:
        if temporary is not None and temporary.exists():
            temporary.unlink()


def breadcrumbs(directory, root, title, website_parent, website_url):
    parts = directory.relative_to(root).parts
    labels = [title] + list(parts)
    crumbs = []
    if website_parent:
        href = website_url or "../" * (len(parts) + 1)
        crumbs.append('<a href="{}">{}</a>'.format(html.escape(href, quote=True), html.escape(website_parent)))
    # The current folder is already the page heading; show only its ancestors here.
    for depth, label in enumerate(labels[:-1]):
        href = "../" * (len(parts) - depth)
        crumbs.append('<a href="{}">{}</a>'.format(href, html.escape(label)))
    return '<span aria-hidden="true">/</span>'.join(crumbs)


def build_tree(root, title, website_parent=None, descriptions=None, introduction="", website_url=None):
    """Build indexes in a public tree, treating existing websites as opaque."""
    root = Path(root)
    if root.is_symlink() or not root.is_dir():
        raise ValueError("Expected a real public directory: {}".format(root))
    template = Template(TEMPLATE.read_text(encoding="utf-8"))
    descriptions = descriptions or {}
    generated = []

    def visit(directory):
        output = directory / "index.html"
        if has_website_index(directory):
            # A newly added website takes precedence over our former listing.
            if is_generated(output):
                output.unlink()
            return

        entries = sorted(
            (path for path in directory.iterdir()
             if not path.name.startswith(".") and not path.is_symlink()
             and path.name != "index.html" and (path.is_file() or path.is_dir())),
            key=lambda path: (not path.is_dir(), path.name.casefold(), path.name),
        )
        rows = []
        folders = 0
        for path in entries:
            folder = path.is_dir()
            href = quote(path.name, safe="") + ("/" if folder else "")
            name = path.name + ("/" if folder else "")
            if folder:
                folders += 1
                metadata = "Website" if has_website_index(path) else "Folder"
                visit(path)
            else:
                kind = path.suffix[1:].upper() or "File"
                metadata = "{} · {}".format(kind, file_size(path.stat().st_size))
            content = entry_content(
                name, descriptions.get(path.relative_to(root).as_posix()), folder
            )
            rows.append(
                '      <li class="entry"><a class="entry-link" href="{}">'
                '<span class="entry-main">{}</span>'
                '<span class="entry-meta">{}</span></a></li>'.format(
                    html.escape(href, quote=True), content, html.escape(metadata)
                )
            )
        files = len(entries) - folders
        counts = []
        for count, singular in ((folders, "folder"), (files, "file")):
            if count:
                counts.append("{} {}{}".format(count, singular, "" if count == 1 else "s"))
        if not rows:
            rows.append('      <li class="entry"><p>No files in this folder.</p></li>')
        current_description = introduction if directory == root else descriptions.get(directory.relative_to(root).as_posix())
        parent_link = '' if directory == root else '<a class="parent-link" href="../">Up one folder</a>'
        content = template.substitute(
            title=html.escape(title if directory == root else directory.name),
            breadcrumbs=breadcrumbs(directory, root, title, website_parent, website_url),
            parent_link=parent_link,
            description=description_markup(current_description, "directory-description", "p"),
            rows="\n".join(rows), summary=" · ".join(counts) or "Empty folder",
        )
        write_if_changed(output, content)
        generated.append(output)

    visit(root)
    return generated


def main():
    pages = []
    descriptions = load_descriptions()
    for relative, title, website_url in (
        ("dev", "Development", "https://ignacioflores.com/"),
        ("share", "Shared files", "https://ignacioflores.com/"),
        ("main/pdf", "PDF files", None),
    ):
        settings = descriptions.get(relative, {})
        pages.extend(build_tree(
            REPOSITORY / relative, title, "Main website", settings.get("entries"),
            settings.get("intro"), website_url,
        ))
    print("Prepared {} static directory pages.".format(len(pages)))


if __name__ == "__main__":
    main()
